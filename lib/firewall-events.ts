/**
 * Firewall audit-trail classification.
 *
 * Pure and free of any server import, so it can be exercised directly by the
 * test runner and reused by both the server and the client boundary.
 */

import type { FirewallEvent } from "./scanner/types.ts";

/**
 * Package coordinates that appear only in the automated test suite.
 *
 * These are real strings a test passed to the preflight, not real installations.
 * They exist so an operational view of the trail can be separated from test
 * noise. The stored events themselves are never touched.
 */
const TEST_FIXTURE_COORDINATES = [
  "d0-safe-fixture",
  "d0-vuln-fixture",
  "d0-review-fixture",
  "d0-outage-fixture",
  "left-pad",
  "x@1.0.0",
];

function matchesFixture(value: string): boolean {
  const bare = value.split("@")[0];
  const scoped = bare.startsWith("@") ? (bare.split("/")[1] ?? bare) : bare;
  return TEST_FIXTURE_COORDINATES.some((t) => bare === t || scoped === t || value === t);
}

/**
 * True when a stored firewall event was generated by the automated test suite.
 *
 * This is a documented, name-based heuristic — not a structural flag. The
 * original events predate the `source` field and nothing in the record marks
 * provenance, so there is no honest way to be certain.
 *
 * It is deliberately conservative: an event with no coordinates (a rejected
 * command) is NOT claimed to be a test, because a real rejected npm install
 * also has none. Only positive matches count.
 */
export function isTestGeneratedFirewallEvent(event: {
  coordinates?: string[];
  command?: string[];
}): boolean {
  const coords = event.coordinates ?? [];
  if (coords.length === 0) return false;
  return coords.some(matchesFixture);
}

/**
 * Split the stored firewall trail into operational and test-generated events.
 *
 * All three values are returned so no caller can accidentally present a
 * filtered number as the whole history. Stored records are historical fact and
 * are never rewritten, reclassified in place, or deleted here.
 */
export function partitionFirewallEvents(events: FirewallEvent[]): {
  rawTotal: number;
  operational: FirewallEvent[];
  testGenerated: FirewallEvent[];
} {
  const operational: FirewallEvent[] = [];
  const testGenerated: FirewallEvent[] = [];
  for (const e of events) {
    (isTestGeneratedFirewallEvent(e) ? testGenerated : operational).push(e);
  }
  return { rawTotal: events.length, operational, testGenerated };
}